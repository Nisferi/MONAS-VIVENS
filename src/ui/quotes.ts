const BY_STAGE: Record<Stage, Quote[]> = {
  genesis: CREATION,
  morpho: FORM,
  mind: MIND,
  crisis: CRISIS,
  respite: MIND,
  aftermath: AFTERMATH,
};

/** Цитата фазы; индекс детерминирован от тика (смена примерно раз в 40 c при ×1). */
export function pickQuote(stage: Stage, tickNo: number): Quote {
  const pool = BY_STAGE[stage];
  return pool[Math.floor(tickNo / 400) % pool.length] as Quote;
}
